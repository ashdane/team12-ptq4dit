"""Image archives and provenance checks shared by generation and ADM evaluation."""
import hashlib
import json
from pathlib import Path
import zipfile

import numpy as np

PAPER_URL = 'https://arxiv.org/html/2405.16005v2'
METRICS = ('FID', 'sFID', 'IS', 'Precision')


def sha256(path):
    h = hashlib.sha256()
    with Path(path).open('rb') as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b''):
            h.update(block)
    return h.hexdigest()


def write_json(path, data):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    temp = path.with_suffix(path.suffix + '.tmp')
    temp.write_text(json.dumps(data, indent=2, allow_nan=False) + '\n')
    temp.replace(path)


def npz_shape(path):
    """Read the array header without loading a multi-GB image archive."""
    with zipfile.ZipFile(path) as z, z.open('arr_0.npy') as f:
        version = np.lib.format.read_magic(f)
        if version == (1, 0):
            shape, order, dtype = np.lib.format.read_array_header_1_0(f)
        elif version == (2, 0):
            shape, order, dtype = np.lib.format.read_array_header_2_0(f)
        else:
            raise ValueError(f'Unsupported NPY header version: {version}')
    if len(shape) != 4 or shape[-1] != 3 or dtype != np.uint8 or order:
        raise ValueError('Expected C-order NHWC uint8 images in arr_0')
    return shape


def batch_ranges(count, batch):
    if min(count, batch) < 1:
        raise ValueError('Image and batch counts must be positive')
    return [(start, min(batch, count-start)) for start in range(0, count, batch)]


def pack_shards(directory, output, count, batch, size):
    """Stream batches into an uncompressed NPZ without a second full-image copy."""
    output = Path(output)
    temp = output.with_suffix('.npz.tmp')
    try:
        with zipfile.ZipFile(temp, 'w', compression=zipfile.ZIP_STORED, allowZip64=True) as z:
            with z.open('arr_0.npy', 'w', force_zip64=True) as dest:
                np.lib.format.write_array_header_2_0(dest, dict(
                    descr=np.dtype('uint8').str, fortran_order=False,
                    shape=(count, size, size, 3)))
                for start, n in batch_ranges(count, batch):
                    a = np.load(Path(directory)/f'{start:06d}.npy', mmap_mode='r', allow_pickle=False)
                    if a.shape != (n, size, size, 3) or a.dtype != np.uint8:
                        raise ValueError(f'Invalid image shard at {start}')
                    dest.write(a.tobytes(order='C'))
        temp.replace(output)
    finally:
        temp.unlink(missing_ok=True)


def validate_manifests(manifests):
    """Fail rather than compare mismatched or incomplete generation runs."""
    if not manifests:
        raise ValueError('No generation manifests')
    base = manifests[0]
    fields = ('checkpoint_sha256', 'dit_commit', 'source_sha256', 'image_size', 'num_samples',
              'batch_size', 'steps', 'cfg', 'seed', 'vae', 'vae_revision', 'scope', 'attention')
    for m in manifests:
        if m['status'] != 'complete':
            raise ValueError('Generation has not completed')
        for key in fields:
            if m[key] != base[key]:
                raise ValueError(f'Cannot compare runs with different {key}')
    return base


def deltas(rows, baseline='fp32'):
    base = next((r for r in rows if r['mode'] == baseline), None)
    if base is None:
        raise ValueError(f'Missing baseline {baseline}')
    return [dict(r, **{f'{key}_delta_vs_{baseline}': r[key]-base[key] for key in METRICS})
            for r in rows]


